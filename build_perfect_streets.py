import math
import json

def haversine(p1, p2):
    lat1, lon1 = p1
    lat2, lon2 = p2
    R = 6371000 # m
    phi1 = math.radians(lat1)
    phi2 = math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi/2)**2 + math.cos(phi1)*math.cos(phi2)*math.sin(dlambda/2)**2
    return 2 * R * math.atan2(math.sqrt(a), math.sqrt(1 - a))

def dense_street_path(keypoints, max_gap_m=12.0):
    result = []
    for i in range(len(keypoints) - 1):
        p1 = keypoints[i]
        p2 = keypoints[i + 1]
        dist = haversine(p1, p2)
        steps = max(1, int(math.ceil(dist / max_gap_m)))
        for s in range(steps):
            t = s / float(steps)
            lat = p1[0] + (p2[0] - p1[0]) * t
            lng = p1[1] + (p2[1] - p1[1]) * t
            result.append([round(lat, 5), round(lng, 5)])
    result.append([round(keypoints[-1][0], 5), round(keypoints[-1][1], 5)])
    return result

